/// All of the potential types of bodies when reading from a PCFS Sata channel.
#[derive(Clone, Debug, PartialEq, Eq, Valuable)]
pub enum SataRequestBody {
	/// A request to set readonly/not-readonly for a path.
	ChangeMode(SataChangeModePacketBody),
	/// A request to change the active owner for a path, always errors.
	ChangeOwner(SataChangeOwnerPacketBody),
	/// A request to create a directory.
	CreateDirectory(SataCreateDirectoryPacketBody),
	/// Close an already open file.
	CloseFile(SataCloseFilePacketBody),
	/// Close an already open directory.
	CloseFolder(SataCloseFolderPacketBody),
	/// A request to get information about a particular file path.
	GetInfoByQuery(SataGetInfoByQueryPacketBody),
	/// A request to open a file.
	OpenFile(SataOpenFilePacketBody),
	/// A request to open a folder, and it's directory contents.
	OpenFolder(SataOpenFolderPacketBody),
	/// A ping request coming in.
	Ping(SataPingPacketBody),
	/// List the files, and folders within a directory (non recursive).
	ReadDirectory(SataReadDirPacketBody),
	/// A request to read actual bytes from a file.
	ReadFile(SataReadFilePacketBody),
	/// A request to remove a file from the filesystem.
	Remove(SataRemovePacketBody),
	/// A request to rewind a directory iterator.
	Rewind(SataRewindDirPacketBody),
	/// Get file information about a particular file.
	StatFile(SataStatFilePacketBody),
	/// Write to a file that is already open.
	WriteFile(SataWriteFilePacketBody),
}

impl SataRequestBody {
	/// Parse the body of a SATA request coming in.
	///
	/// ## Errors
	///
	/// If we cannot successfully parse the command because it is corrupt, or
	/// in another way invalid.
	pub fn parse_command(command: u32, body: Bytes) -> Result<SataRequestBody, NetworkParseError> {
		match command {
			0x0 => {
				SataCreateDirectoryPacketBody::try_from(body).map(SataRequestBody::CreateDirectory)
			}
			0x1 => SataOpenFolderPacketBody::try_from(body).map(SataRequestBody::OpenFolder),
			0x2 => SataReadDirPacketBody::try_from(body).map(SataRequestBody::ReadDirectory),
			0x3 => SataRewindDirPacketBody::try_from(body).map(SataRequestBody::Rewind),
			0x4 => SataCloseFolderPacketBody::try_from(body).map(SataRequestBody::CloseFolder),
			0x5 => SataOpenFilePacketBody::try_from(body).map(SataRequestBody::OpenFile),
			0x6 => SataReadFilePacketBody::try_from(body).map(SataRequestBody::ReadFile),
			0x7 => SataWriteFilePacketBody::try_from(body).map(SataRequestBody::WriteFile),
			0xB => SataStatFilePacketBody::try_from(body).map(SataRequestBody::StatFile),
			0xD => SataCloseFilePacketBody::try_from(body).map(SataRequestBody::CloseFile),
			0xE => SataRemovePacketBody::try_from(body).map(SataRequestBody::Remove),
			0x10 => {
				SataGetInfoByQueryPacketBody::try_from(body).map(SataRequestBody::GetInfoByQuery)
			}
			0x12 => SataChangeOwnerPacketBody::try_from(body).map(SataRequestBody::ChangeOwner),
			0x13 => SataChangeModePacketBody::try_from(body).map(SataRequestBody::ChangeMode),
			0x14 => SataPingPacketBody::try_from(body).map(SataRequestBody::Ping),
			val => {
				debug!(
					command.id = command,
					command.leftover = format!("{:02X?}", body),
					"Unknown SATA Command ID..."
				);
				Err(SataProtocolError::UnknownPacketType(val).into())
			}
		}
	}
}

#[cfg(feature = "servers")]
/// Construct a response to send as a response to a SATA packet.
fn construct_sata_response<Ty: Into<Bytes>>(
	request_header: &SataPacketHeader,
	flags: u32,
	body: Ty,
) -> Result<Bytes, PCFSApiError> {
	let body_as_bytes: Bytes = body.into();
	let mut new_buff = BytesMut::with_capacity(0x20 + body_as_bytes.len());

	new_buff.put_u32(
		u32::try_from(body_as_bytes.len())
			.map_err(|_| PCFSApiError::PacketTooLargeForSata(body_as_bytes.len()))?,
	);
	new_buff.put_u32(request_header.packet_id);
	new_buff.put_u32(flags);
	// Yeah bro we're totally the same version...
	new_buff.put_u32(if request_header.version != 0 {
		request_header.version
	} else {
		DEFAULT_PCFS_VERSION
	});
	// Calculate epoch, and wrap around...
	new_buff.put_u32(
		u32::try_from(
			SystemTime::now()
				.duration_since(SystemTime::UNIX_EPOCH)
				.unwrap_or(Duration::from_secs(0))
				.as_secs()
				.rem_euclid(u64::from(u32::MAX)),
		)
		.unwrap_or(u32::MAX),
	);
	// Put our PID, and appropriate padding.
	new_buff.put_u32(*PID);
	new_buff.extend([0; 8]);
	// Now we can finally add our body!
	new_buff.extend(body_as_bytes);

	Ok(new_buff.freeze())
}

/// Move to a particular location inside of a file.
#[derive(Copy, Clone, Debug, PartialEq, Eq, Hash, PartialOrd, Ord, Valuable)]
pub enum MoveToFileLocation {
	/// Move to the beginning of the file.
	Begin,
	/// Move nowhere.
	Current,
	/// Move to the end of a file.
	End,
}

impl From<&MoveToFileLocation> for u32 {
	fn from(value: &MoveToFileLocation) -> u32 {
		match *value {
			MoveToFileLocation::Begin => 0,
			MoveToFileLocation::Current => 1,
			MoveToFileLocation::End => 2,
		}
	}
}

impl From<MoveToFileLocation> for u32 {
	fn from(value: MoveToFileLocation) -> u32 {
		Self::from(&value)
	}
}

impl TryFrom<u32> for MoveToFileLocation {
	type Error = SataProtocolError;

	fn try_from(value: u32) -> Result<Self, Self::Error> {
		match value {
			0 => Ok(Self::Begin),
			1 => Ok(Self::Current),
			2 => Ok(Self::End),
			val => Err(SataProtocolError::UnknownFileLocation(val)),
		}
	}
}

