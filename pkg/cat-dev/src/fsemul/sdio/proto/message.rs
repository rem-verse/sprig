//! An SDIO "message", basically a log line that's coming from the SDIO/CAT-DEV
//! interface.

use crate::{errors::NetworkParseError, fsemul::sdio::errors::SDIOProtocolError};
use bytes::{BufMut, Bytes, BytesMut};
use valuable::{
	EnumDef, Enumerable, Fields, NamedField, NamedValues, StructDef, Structable, Valuable, Value,
	Variant, VariantDef, Visit,
};

#[derive(Clone, Debug, PartialEq, Eq)]
pub enum SdioControlMessage {
	/// A message to print to the screen.
	Printf(Bytes, String),
	/// TODO(mythra): Currently unknown, mostly used for scientist.
	Unknown(Vec<u8>),
	/// TODO(mythra): also very unknown, mostly used for debugging.
	UnknownTwo(Vec<u8>),
}

static SDIO_CONTROL_MESSAGE_VARIANTS: &[VariantDef<'static>] = &[
	VariantDef::new("Printf", Fields::Unnamed(2)),
	VariantDef::new("Unknown", Fields::Unnamed(1)),
	VariantDef::new("UnknownTwo", Fields::Unnamed(3)),
];

impl Enumerable for SdioControlMessage {
	fn definition(&self) -> EnumDef<'_> {
		EnumDef::new_static("SdioControlMessage", SDIO_CONTROL_MESSAGE_VARIANTS)
	}

	fn variant(&self) -> Variant<'_> {
		match self {
			SdioControlMessage::Printf(_, _) => Variant::Static(&SDIO_CONTROL_MESSAGE_VARIANTS[0]),
			SdioControlMessage::Unknown(_) => Variant::Static(&SDIO_CONTROL_MESSAGE_VARIANTS[1]),
			SdioControlMessage::UnknownTwo(_) => Variant::Static(&SDIO_CONTROL_MESSAGE_VARIANTS[2]),
		}
	}
}

impl Valuable for SdioControlMessage {
	fn as_value(&self) -> Value<'_> {
		Value::Enumerable(self)
	}

	fn visit(&self, visitor: &mut dyn Visit) {
		match self {
			SdioControlMessage::Printf(extra, buff) => {
				visitor.visit_unnamed_fields(&[
					Valuable::as_value(&format!("{extra:02X?}")),
					Valuable::as_value(&buff),
				]);
			}
			SdioControlMessage::Unknown(buff) | SdioControlMessage::UnknownTwo(buff) => {
				visitor.visit_unnamed_fields(&[Valuable::as_value(&buff)]);
			}
		}
	}
}

/// Handle a Write Request coming over the SDIO Control port.
#[derive(Debug, PartialEq, Eq)]
pub struct SdioControlMessageRequest {
	messages: Vec<SdioControlMessage>,
}

impl SdioControlMessageRequest {
	#[must_use]
	pub const fn new(messages: Vec<SdioControlMessage>) -> Self {
		Self { messages }
	}

	#[must_use]
	pub const fn messages(&self) -> &Vec<SdioControlMessage> {
		&self.messages
	}

	#[must_use]
	pub fn messages_owned(self) -> Vec<SdioControlMessage> {
		self.messages
	}
}

impl TryFrom<&SdioControlMessageRequest> for Bytes {
	type Error = NetworkParseError;

	#[allow(
		// We will actually loop in the future.
		clippy::never_loop,
	)]
	fn try_from(value: &SdioControlMessageRequest) -> Result<Self, Self::Error> {
		let inner_size = {
			let mut size = 0_usize;
			for msg in value.messages() {
				match msg {
					SdioControlMessage::Printf(_, buff) => {
						size += buff.len();
					}
					SdioControlMessage::Unknown(un) | SdioControlMessage::UnknownTwo(un) => {
						size += un.len();
					}
				}
			}
			size
		};
		let final_size = inner_size + (8 + (value.messages().len() * 4));
		if final_size > 512 {
			return Err(SDIOProtocolError::PrintfInvalidSize(final_size).into());
		}

		let mut final_buff = BytesMut::with_capacity(512);
		final_buff.put_u16_le(8);
		final_buff.put_u16_le(u16::try_from(final_size).unwrap_or(u16::MAX));

		for msg in &value.messages {
			match msg {
				SdioControlMessage::Printf(extra, buff) => {
					final_buff.put_u16_le(4);
					final_buff.extend(extra);
					final_buff.extend(buff.as_bytes());
					break;
				}
				SdioControlMessage::Unknown(buff) => {
					final_buff.put_u16_le(9);
					final_buff.extend(buff);
					break;
				}
				SdioControlMessage::UnknownTwo(buff) => {
					final_buff.put_u16_le(8);
					final_buff.extend(buff);
					break;
				}
			}
		}

		if final_buff.len() < 512 {
			final_buff.extend(BytesMut::zeroed(512 - final_buff.len()));
		}

		Ok(final_buff.freeze())
	}
}

impl TryFrom<SdioControlMessageRequest> for Bytes {
	type Error = NetworkParseError;

	fn try_from(value: SdioControlMessageRequest) -> Result<Self, Self::Error> {
		Self::try_from(&value)
	}
}

impl TryFrom<Bytes> for SdioControlMessageRequest {
	type Error = NetworkParseError;

	#[allow(
    // We will actually loop in the future.
    clippy::never_loop,
		// We will loop in the future probably.
		unused_assignments,
  )]
	fn try_from(value: Bytes) -> Result<Self, Self::Error> {
		if value.len() != 512 {
			return Err(SDIOProtocolError::PrintfInvalidSize(value.len()).into());
		}
		if value[0] != 8 {
			return Err(SDIOProtocolError::UnknownPrintfPacketType(value[0]).into());
		}

		let _character_length = u16::from_le_bytes([value[0x2], value[0x3]]);
		let mut messages = Vec::with_capacity(1);
		let mut read_size = 0;
		loop {
			let base_offset = 4 + (messages.len() * 4) + read_size;
			let message_ty = u16::from_le_bytes([value[base_offset], value[base_offset + 1]]);

			// puVar1 & bytes to send after two u16s.
			if message_ty == 4 {
				// first 6 bytes are unknown
				let mut buff = value.slice(base_offset + 8..);
				if let Some(eol) = buff.iter().position(|item| *item == 0x0) {
					buff.truncate(eol);
				}
				messages.push(SdioControlMessage::Printf(
					value.slice(base_offset + 2..base_offset + 8),
					String::from_utf8_lossy(&buff).to_string(),
				));
				read_size += buff.len();
				// These message types consume the whole buffer probably idk
				break;
			} else if message_ty == 9 {
				let unknown_data = value.slice(base_offset + 2..).to_vec();
				read_size += unknown_data.len();
				messages.push(SdioControlMessage::Unknown(unknown_data));
				break;
			} else if message_ty == 8 {
				let unknown_data = value.slice(base_offset + 2..).to_vec();
				read_size += unknown_data.len();
				messages.push(SdioControlMessage::UnknownTwo(unknown_data));
				break;
			}

			return Err(SDIOProtocolError::UnknownPrintfMessageType(message_ty).into());
		}

		Ok(Self { messages })
	}
}

const MESSAGE_REQUEST_FIELDS: &[NamedField<'static>] = &[NamedField::new("messages")];

impl Structable for SdioControlMessageRequest {
	fn definition(&self) -> StructDef<'_> {
		StructDef::new_static(
			"SdioControlMessageRequest",
			Fields::Named(MESSAGE_REQUEST_FIELDS),
		)
	}
}

impl Valuable for SdioControlMessageRequest {
	fn as_value(&self) -> Value<'_> {
		Value::Structable(self)
	}

	fn visit(&self, visitor: &mut dyn Visit) {
		visitor.visit_named_fields(&NamedValues::new(
			MESSAGE_REQUEST_FIELDS,
			&[Valuable::as_value(&self.messages)],
		));
	}
}

